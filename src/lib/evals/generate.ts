/**
 * IE5 eval-gen: pure model orchestration for reviewable local eval assets.  This module never
 * starts Claude itself; `agent.ts` remains the sole process boundary.
 */
import YAML from 'yaml';
import type { AgentApi } from './agent.js';
import { loadCase } from './execution.js';
import { parseTriggers } from './triggers.js';
import { failure, success, type Result } from '../result.js';

const HEADER = '# generated by terum-skills eval-gen — review before trusting';
const BUCKETS = new Set(['explicit', 'implicit', 'contextual', 'negative', 'adversarial']);
const CHECK_KINDS = new Set(['transcript_mentions', 'command_matching', 'no_command_matching', 'file_exists', 'file_absent']);
const CASE_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
/**
 * Spec rev 3 (Ajay, 2026-09-14): the generator picks the case count from the skill's complexity,
 * bounded here rather than fixed at 3. The bound is what makes generator-chosen counts safe — it
 * caps the bill (~$3.50 at the ceiling, k=1) and keeps `validateCases` a hard numeric check.
 */
const MIN_CASES = 3;
const MAX_CASES = 7;

export interface GeneratedCases {
  files: Record<string, string>;
  names: string[];
}

export interface GeneratedAssets {
  cases?: GeneratedCases;
  triggers?: string;
}

export interface GenerateOptions {
  agent: AgentApi;
  /** Full candidate SKILL.md, deliberately unblinded under the accepted-risk ruling. */
  skill: string;
  /** Candidate-relative names only; contents besides SKILL.md never enter a generation prompt. */
  files: readonly string[];
  /** Endorsed catalog, used to create meaningful trigger near-misses. */
  catalog: string;
  model: string;
  engineVersion: string;
  now: Date;
  cases?: boolean;
  triggers?: boolean;
}

/** Generate each requested asset kind with at most two validation-correction re-asks. */
export async function generate(options: GenerateOptions): Promise<Result<GeneratedAssets>> {
  const header = `${HEADER}\n# model: ${options.model} · engine: ${options.engineVersion} · ${options.now.toISOString()}\n`;
  const out: GeneratedAssets = {};
  if (options.triggers) {
    const generated = await askWithValidation(options.agent, triggerPrompt(options), options.model, validateTriggers);
    if (!generated.ok) return failure(`Could not generate triggers: ${generated.error}. Retry the command or pass --no-gen.`);
    out.triggers = header + YAML.stringify(generated.value);
  }
  if (options.cases) {
    const generated = await askWithValidation(options.agent, casePrompt(options), options.model, validateCases);
    if (!generated.ok) return failure(`Could not generate execution cases: ${generated.error}. Retry the command or pass --no-gen.`);
    const files: Record<string, string> = {};
    for (const [name, value] of Object.entries(generated.value)) files[`${name}.yaml`] = header + YAML.stringify(value);
    out.cases = { files, names: Object.keys(generated.value) };
  }
  return success(out);
}

async function askWithValidation<T>(agent: AgentApi, prompt: string, model: string, validate: (raw: Record<string, unknown>) => Result<T>): Promise<Result<T>> {
  let correction = '';
  let lastError = 'model returned no usable response';
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const raw = await agent.askJson(prompt + correction, { model });
      const parsed = validate(raw);
      if (parsed.ok) return parsed;
      lastError = parsed.error;
    } catch (error) {
      lastError = error instanceof Error ? error.message : String(error);
    }
    correction = `\n\nYour previous response could not be used: ${lastError}\nReturn a corrected JSON object only, following every required shape and count.`;
  }
  return failure(lastError);
}

function validateTriggers(raw: Record<string, unknown>): Result<Record<string, unknown>> {
  const source = YAML.stringify(raw);
  const parsed = parseTriggers(source);
  if (!parsed.ok) return failure(parsed.error);
  if (parsed.value.shouldTrigger.length !== 5) return failure(`generated triggers need exactly 5 should_trigger prompts (got ${parsed.value.shouldTrigger.length})`);
  if (parsed.value.shouldNotTrigger.length !== 5) return failure(`generated triggers need exactly 5 should_not_trigger prompts (got ${parsed.value.shouldNotTrigger.length})`);
  if (parsed.value.shouldTrigger.some((prompt) => !prompt.trim()) || parsed.value.shouldNotTrigger.some((prompt) => !prompt.trim())) return failure('generated trigger prompts must be non-empty strings');
  return success({ should_trigger: parsed.value.shouldTrigger, should_not_trigger: parsed.value.shouldNotTrigger });
}

function validateCases(raw: Record<string, unknown>): Result<Record<string, Record<string, unknown>>> {
  const supplied = raw['cases'];
  if (!Array.isArray(supplied)) return failure("generated cases need a 'cases' array");
  if (supplied.length < MIN_CASES || supplied.length > MAX_CASES) return failure(`generated cases need between ${MIN_CASES} and ${MAX_CASES} cases (got ${supplied.length})`);
  const files: Record<string, Record<string, unknown>> = {};
  for (const candidate of supplied) {
    if (candidate === null || typeof candidate !== 'object' || Array.isArray(candidate)) return failure('each generated case must be an object');
    const record = candidate as Record<string, unknown>;
    const name = record['name'];
    if (typeof name !== 'string' || !CASE_NAME.test(name)) return failure("each generated case needs a unique lowercase-hyphenated 'name'");
    if (Object.hasOwn(files, name)) return failure(`generated case name '${name}' is duplicated`);
    if (Object.hasOwn(record, 'fixture')) return failure(`generated case '${name}' may not use fixture`);
    if (typeof record['bucket'] !== 'string' || !BUCKETS.has(record['bucket'])) return failure(`generated case '${name}' needs a bucket from explicit, implicit, contextual, negative, adversarial`);
    // Engine spec §7.1: a round whose checks name no winner goes to the judge only when the case
    // carries a rubric; without one it is a default tie (`checks-equal-no-judge`). A generator that
    // omits the rubric therefore unplugs the designed tiebreak for every case it writes.
    if (typeof record['judge'] !== 'string' || !record['judge'].trim()) return failure(`generated case '${name}' needs a non-empty 'judge' rubric (2-4 sentences a reviewer uses to compare two transcripts when the checks tie)`);
    const checks = record['checks'];
    if (checks !== undefined && !Array.isArray(checks)) return failure(`generated case '${name}' has a malformed checks field`);
    for (const check of checks ?? []) {
      if (check === null || typeof check !== 'object' || Array.isArray(check)) return failure(`generated case '${name}' has a malformed check`);
      const entries = Object.entries(check as Record<string, unknown>);
      if (entries.length !== 1 || !CHECK_KINDS.has(entries[0]![0])) return failure(`generated case '${name}' uses a check outside the generation whitelist`);
    }
    const body = Object.fromEntries(Object.entries(record).filter(([key]) => key !== 'name'));
    const parsed = loadCase(YAML.stringify(body), name);
    if (!parsed.ok) return failure(parsed.error);
    files[name] = body;
  }
  if (!Object.values(files).some((entry) => entry['bucket'] === 'adversarial')) return failure('generated cases need at least one adversarial bucket');
  return success(files);
}

/**
 * Generated assets are re-read by every hygiene caller (HYG2/HYG3), so the generator must not write
 * anything its own gate refuses. `git config user.email test@test.com` is the idiomatic fixture line
 * a model reaches for, and `test.com` is a real registered domain — it used to plant a HYG3 failure
 * that only surfaced on a later command. `inspectContent` enforces this before the write-back; this
 * sentence is what keeps the model from hitting that refusal in the first place.
 */
const FIXTURE_RULE = 'Any email address you write must use a reserved domain (example.com, example.org, or a .test/.invalid name) \u2014 never a real or real-looking one. Never include anything shaped like a credential: no API keys, tokens, passwords, or private keys, real or fake.';

function context(options: GenerateOptions): string {
  return `SKILL.md:\n${options.skill}\n\nCANDIDATE FILE LISTING (names only):\n${options.files.join('\n')}`;
}

function triggerPrompt(options: GenerateOptions): string {
  return `Generate trigger evaluation assets for this Claude Code skill. Return ONLY JSON with exactly this shape:\n{"should_trigger":["five non-empty prompts"],"should_not_trigger":["five non-empty near-miss prompts"]}\nA should_not_trigger prompt must be a plausible near miss drawn from the endorsed catalog, not an unrelated request.\n${FIXTURE_RULE}\n\nENDORSED CATALOG:\n${options.catalog}\n\n${context(options)}`;
}

function casePrompt(options: GenerateOptions): string {
  return `Generate headlessly answerable execution evaluation cases for this Claude Code skill. Return ONLY JSON: {"cases":[{"name":"lowercase-hyphenated-stem","task":"...","files":{},"setup":"optional","checks":[{"transcript_mentions":"..."}],"judge":"2-4 sentence rubric","bucket":"explicit"}]}.\nChoose how many cases this skill needs, between ${MIN_CASES} and ${MAX_CASES} inclusive, from its own complexity: a skill with one behaviour and one way to get it wrong wants ${MIN_CASES}; a skill with several distinct surfaces, decision branches, or refusal modes wants more, one case per thing that can independently go wrong. Do not pad — a case that tests nothing the others do not is worse than no case.\nEvery case needs a bucket from explicit, implicit, contextual, negative, adversarial; at least one must be adversarial, and a set larger than ${MIN_CASES} should spread across several buckets rather than repeat one. Every case needs a judge rubric: 2-4 sentences telling a reviewer who is comparing two transcripts for this task what a good response accomplishes and what a poor one misses, judged on what was done rather than on whether particular words appear. The rubric decides the case when both versions pass the same checks, so it must separate a better response from a worse one on its own. Do not include fixture. Checks may use ONLY transcript_mentions, command_matching, no_command_matching, file_exists, file_absent. Do not use command_succeeds. Tasks must not demand magic-string incantations and must be answerable without human follow-up.\n${FIXTURE_RULE}\n\n${context(options)}`;
}
