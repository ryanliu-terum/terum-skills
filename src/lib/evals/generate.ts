/**
 * IE5 eval-gen: pure model orchestration for reviewable local eval assets.  This module never
 * starts Claude itself; `agent.ts` remains the sole process boundary. The one subprocess it causes
 * is the dry-run of a generated case's `setup` hook, through `execution.ts`'s own seeding path.
 */
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import YAML from 'yaml';
import { AgentRunError, type AgentApi } from './agent.js';
import { casePathViolation, dryRunCase, dryRunSuite, loadCase, loadSuite, patchApplies } from './execution.js';
import { hygieneFrontmatter } from './hygiene.js';
import { parseTriggers } from './triggers.js';
import { failure, success, type Result } from '../result.js';

const HEADER = '# generated by terum-skills eval-gen — review before trusting';
const BUCKETS = new Set(['explicit', 'implicit', 'contextual', 'negative', 'adversarial']);
const CHECK_KINDS = new Set(['transcript_mentions', 'transcript_omits', 'command_matching', 'no_command_matching', 'file_exists', 'file_absent']);
const CASE_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
/**
 * Spec rev 3 (Ajay, 2026-09-14): the generator picks the case count from the skill's complexity,
 * bounded here rather than fixed at 3. The bound is what makes generator-chosen counts safe — it
 * caps the bill (~$3.50 at the ceiling, k=1) and keeps `validateCases` a hard numeric check.
 */
const MIN_CASES = 3;
const MAX_CASES = 7;
/**
 * IE6 §7.2: head-to-head raises the FLOOR only. Three is too thin a denominator for a
 * comparison anyone will act on, and the cases are cheaper here than the arms; #236's
 * generator-chosen count still picks the number, just from a narrower range.
 */
const MIN_HEAD_TO_HEAD_CASES = 5;
/** §7.3: long enough for a real task description, short enough that a human reads it. */
export const BRIEF_MAX = 1_500;

export type NeutralityVerdict =
  | { kind: 'ok' }
  | { kind: 'warn'; name: string }
  | { kind: 'refuse'; name: string };

/**
 * IE6 §3.1: the deterministic neutrality check, a PURE function rather than logic inside the
 * correction loop — the supplied-brief path calls it too and must not pay a model round-trip.
 *
 * A multi-token name (hyphenated or spaced) appearing in the brief means the brief is describing
 * the tool, so it refuses. A single-token name is usually an ordinary English word — this project
 * ships skills called `search`, `eval`, `ls`, `run` — and a hard refusal there makes exactly those
 * skills uncomparable, so it warns and continues. No dictionary: the rule is the token count of
 * the NAME, so there is nothing to maintain.
 */
export function checkBriefNeutrality(brief: string, names: readonly string[]): NeutralityVerdict {
  let warned: string | undefined;
  for (const name of names) {
    if (!nameAppears(brief, name)) continue;
    if (name.split(/[^A-Za-z0-9]+/).filter(Boolean).length > 1) return { kind: 'refuse', name };
    warned ??= name;
  }
  return warned === undefined ? { kind: 'ok' } : { kind: 'warn', name: warned };
}

/** Bounded by non-alphanumerics so `ls` does not match inside `tools` or `false`. */
function nameAppears(haystack: string, name: string): boolean {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![A-Za-z0-9])${escaped}(?![A-Za-z0-9])`, 'i').test(haystack);
}

export interface DeriveBriefOptions {
  agent: AgentApi;
  /** Both skills, each with its SKILL.md and file listing. The order given here is irrelevant. */
  skills: readonly { name: string; skill: string; files: readonly string[] }[];
  model: string;
}

export interface DerivedBrief {
  brief: string;
  /** §4 `_meta.brief_order`: the names in the order shown, so the aliasing is auditable. */
  order: string[];
  /** Set when a single-token name survived into the brief — printed above the confirm gate. */
  warning?: string;
}

/**
 * §3.1: derive the shared task brief. Both skills are aliased to `Skill 1` / `Skill 2` and
 * ordered BY NAME, never by which was typed first — a fixed order would put the candidate in
 * the same slot on every run, the position tilt §7.5 swaps judge orderings to avoid.
 */
export async function deriveBrief(options: DeriveBriefOptions): Promise<Result<DerivedBrief>> {
  const ordered = [...options.skills].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const names = ordered.map((entry) => entry.name);
  let warning: string | undefined;
  const prompt = briefPrompt(ordered);
  const result = await askWithValidation<string>(options.agent, prompt, options.model, Buffer.byteLength(prompt, 'utf8'), (raw) => {
    const brief = raw['brief'];
    if (typeof brief !== 'string' || !brief.trim()) return Promise.resolve(failure("the brief must be a non-empty 'brief' string"));
    if (brief.length > BRIEF_MAX) return Promise.resolve(failure(`the brief must be at most ${BRIEF_MAX} characters (got ${brief.length})`));
    const neutrality = checkBriefNeutrality(brief, names);
    if (neutrality.kind === 'refuse') return Promise.resolve(failure(`the brief names '${neutrality.name}'; describe the job, not either tool`));
    warning = neutrality.kind === 'warn' ? neutrality.name : undefined;
    return Promise.resolve(success(brief.trim()));
  });
  if (!result.ok) return failure(`Could not derive a shared brief: ${result.error}. Write one yourself and pass --brief <path>.`);
  return success({ brief: result.value, order: names, ...(warning === undefined ? {} : { warning }) });
}

function briefPrompt(ordered: readonly { skill: string; files: readonly string[] }[]): string {
  const blocks = ordered.map((entry, index) => `SKILL ${index + 1} — SKILL.md:\n${entry.skill}\n\nSKILL ${index + 1} — FILE LISTING (names only):\n${entry.files.join('\n')}`);
  return `Two Claude Code skills do a similar job. Describe THE JOB — not either skill — as a task brief an evaluator will use to write test cases neither skill has seen.\n\nReturn ONLY JSON: {"brief":"..."}.\nThe brief must be plain prose, at most ${BRIEF_MAX} characters, and must NOT name either skill or any tool: a brief that names a tool is describing the tool, not the job. Describe what someone needs done and what a good result looks like.\n\n${blocks.join('\n\n')}`;
}
/**
 * Eval-gen D6 (2026-09-14): `askJson`'s 120 s default was sized for exactly three cases. Rev 3 asks
 * for up to seven and D1 asks each to carry a tool stub, and a 34 KB SKILL.md (single-fix) did not
 * finish in 120 s — three silent timeouts, no receipt. Arm runs get 600 s; generation gets half.
 */
export const GENERATION_TIMEOUT_MS = 300_000;
/**
 * Every YAML the generator writes or re-reads is dumped unfolded. The default 80-column folding
 * picks a `>` scalar for diff-shaped text (a long line, then space-led context lines) and the parse
 * no longer returns the same bytes — a `plants_diff` that validated would not apply once written.
 */
const YAML_OPTIONS = { lineWidth: 0 } as const;

export interface GeneratedCases {
  files: Record<string, string>;
  names: string[];
}

export interface GeneratedAssets {
  cases?: GeneratedCases;
  suite?: { file: string };
  triggers?: string;
}

export interface GenerateOptions {
  agent: AgentApi;
  /** Full candidate SKILL.md, deliberately unblinded under the accepted-risk ruling. */
  skill: string;
  /** Candidate-relative names only; contents besides SKILL.md never enter a generation prompt. */
  files: readonly string[];
  /** Endorsed catalog, used to create meaningful trigger near-misses. */
  catalog: string;
  model: string;
  engineVersion: string;
  now: Date;
  cases?: boolean;
  triggers?: boolean;
  /**
   * IE6 §3.2: head-to-head. When set, the case prompt sees the brief ALONE — no SKILL.md, no
   * file listing — which removes eval-gen's accepted circularity rather than mitigating it.
   */
  brief?: string;
  /** Optional lenient `metadata.eval.shape` value; validity is owned by this generation boundary. */
  shape?: unknown;
  /** Where D3's dry-run sandboxes live; a private temp dir, removed afterwards, when omitted. */
  scratch?: string;
}

/** Generate each requested asset kind with at most two validation-correction re-asks. */
export async function generate(options: GenerateOptions): Promise<Result<GeneratedAssets>> {
  const header = `${HEADER}\n# model: ${options.model} · engine: ${options.engineVersion} · ${options.now.toISOString()}\n`;
  const skillBytes = Buffer.byteLength(options.skill, 'utf8');
  const out: GeneratedAssets = {};
  if (options.triggers) {
    const generated = await askWithValidation(options.agent, triggerPrompt(options), options.model, skillBytes, async (raw) => validateTriggers(raw));
    if (!generated.ok) return failure(`Could not generate triggers: ${generated.error}. Retry the command or pass --no-gen.`);
    out.triggers = header + YAML.stringify(generated.value, YAML_OPTIONS);
  }
  if (options.cases) {
    const scratch = options.scratch ?? await mkdtemp(join(tmpdir(), 'terum-eval-gen-'));
    const skillName = skillNameOf(options.skill);
    let generated: Result<{ kind: 'cases'; cases: Record<string, Record<string, unknown>> } | { kind: 'suite'; file: string }>;
    try {
      const shape = generationShape(options.shape);
      if (!shape.ok) return failure(`Could not generate execution cases: ${shape.error}. Retry the command or pass --no-gen.`);
      // IE6 §3.2: head-to-head fixes the shape to `cases`. A suite plants defects into a
      // repository the generator builds from the skill's own text; from a brief alone that is a
      // longer leap than this mode needs, and the shape choice would vary between reruns of the
      // same pair. The floor rises to MIN_HEAD_TO_HEAD_CASES; #236 still picks the number.
      const headToHead = options.brief !== undefined;
      const shapeValue: GenerationShape = headToHead ? 'cases' : shape.value;
      const floor = headToHead ? MIN_HEAD_TO_HEAD_CASES : MIN_CASES;
      const prompt = headToHead ? casePrompt(options, floor) : suitePrompt(options, shapeValue);
      generated = await askWithValidation(options.agent, prompt, options.model, skillBytes, (raw) => validateExecutionAssets(raw, scratch, shapeValue, skillName, floor));
    } finally {
      if (options.scratch === undefined) await rm(scratch, { recursive: true, force: true });
    }
    if (!generated.ok) return failure(`Could not generate execution cases: ${generated.error}. Retry the command or pass --no-gen.`);
    if (generated.value.kind === 'cases') {
      const files: Record<string, string> = {};
      for (const [name, value] of Object.entries(generated.value.cases)) files[`${name}.yaml`] = header + YAML.stringify(value, YAML_OPTIONS);
      out.cases = { files, names: Object.keys(generated.value.cases) };
    } else out.suite = { file: header + generated.value.file };
  }
  return success(out);
}

type GenerationShape = 'suite' | 'cases' | undefined;

function generationShape(value: unknown): Result<GenerationShape> {
  if (value === undefined || value === null) return success(undefined);
  if (value === 'suite' || value === 'cases') return success(value);
  return failure("SKILL.md metadata.eval.shape must be 'suite' or 'cases'");
}

async function validateExecutionAssets(raw: Record<string, unknown>, scratch: string, fixedShape: GenerationShape, skillName: string | undefined, floor: number = MIN_CASES): Promise<Result<{ kind: 'cases'; cases: Record<string, Record<string, unknown>> } | { kind: 'suite'; file: string }>> {
  const isSuite = Object.hasOwn(raw, 'suite');
  const isCases = Object.hasOwn(raw, 'cases');
  if (isSuite === isCases) return failure("generated execution assets need exactly one of 'suite' or 'cases'");
  if (fixedShape !== undefined && (fixedShape === 'suite') !== isSuite) return failure(`The shape is fixed: return {"${fixedShape}": ${fixedShape === 'suite' ? '...}' : '[...]}'}`);
  if (isCases) {
    const cases = await validateCases(raw, scratch, skillName, floor);
    return cases.ok ? success({ kind: 'cases', cases: cases.value }) : failure(cases.error);
  }
  const suite = await validateSuite(raw, scratch, skillName);
  return suite.ok ? success({ kind: 'suite', file: suite.value }) : failure(suite.error);
}

/**
 * Up to three model calls. A validation failure is the model's to fix and goes back as a correction;
 * an `AgentRunError` (timeout, non-zero exit) is infrastructure, so it is retried once with the
 * prompt UNCHANGED and then reported as itself — before D6 a timeout was appended as "your previous
 * response could not be used: model call timed out", which no model can act on.
 */
async function askWithValidation<T>(agent: AgentApi, prompt: string, model: string, skillBytes: number, validate: (raw: Record<string, unknown>) => Promise<Result<T>>): Promise<Result<T>> {
  let correction = '';
  let lastError = 'model returned no usable response';
  let infrastructureFailures = 0;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const raw = await agent.askJson(prompt + correction, { model, timeoutMs: GENERATION_TIMEOUT_MS });
      const parsed = await validate(raw);
      if (parsed.ok) return parsed;
      lastError = parsed.error;
    } catch (error) {
      lastError = error instanceof Error ? error.message : String(error);
      if (error instanceof AgentRunError) {
        infrastructureFailures += 1;
        if (infrastructureFailures >= 2) return failure(`${lastError} (twice, generating from a ${skillBytes}-byte SKILL.md)`);
        continue;
      }
    }
    correction = `\n\nYour previous response could not be used: ${lastError}\nReturn a corrected JSON object only, following every required shape and count.`;
  }
  return failure(lastError);
}

function validateTriggers(raw: Record<string, unknown>): Result<Record<string, unknown>> {
  const source = YAML.stringify(raw, YAML_OPTIONS);
  const parsed = parseTriggers(source);
  if (!parsed.ok) return failure(parsed.error);
  if (parsed.value.shouldTrigger.length !== 5) return failure(`generated triggers need exactly 5 should_trigger prompts (got ${parsed.value.shouldTrigger.length})`);
  if (parsed.value.shouldNotTrigger.length !== 5) return failure(`generated triggers need exactly 5 should_not_trigger prompts (got ${parsed.value.shouldNotTrigger.length})`);
  if (parsed.value.shouldTrigger.some((prompt) => !prompt.trim()) || parsed.value.shouldNotTrigger.some((prompt) => !prompt.trim())) return failure('generated trigger prompts must be non-empty strings');
  return success({ should_trigger: parsed.value.shouldTrigger, should_not_trigger: parsed.value.shouldNotTrigger });
}

/**
 * Shape first, then the runtime contract: every `files` key passes the same path predicate
 * `seedSandbox` applies (D2), and every case is seeded once in a throwaway sandbox so its `setup`
 * has provably started before it is written into the skill (D3). Both used to surface only at
 * run time — one as a silently dropped case, the other as a dead eval.
 */
async function validateCases(raw: Record<string, unknown>, scratch: string, skillName: string | undefined, floor: number = MIN_CASES): Promise<Result<Record<string, Record<string, unknown>>>> {
  const supplied = raw['cases'];
  if (!Array.isArray(supplied)) return failure("generated cases need a 'cases' array");
  if (supplied.length < floor || supplied.length > MAX_CASES) return failure(`generated cases need between ${floor} and ${MAX_CASES} cases (got ${supplied.length})`);
  const files: Record<string, Record<string, unknown>> = {};
  for (const candidate of supplied) {
    if (candidate === null || typeof candidate !== 'object' || Array.isArray(candidate)) return failure('each generated case must be an object');
    const record = candidate as Record<string, unknown>;
    const name = record['name'];
    if (typeof name !== 'string' || !CASE_NAME.test(name)) return failure("each generated case needs a unique lowercase-hyphenated 'name'");
    if (Object.hasOwn(files, name)) return failure(`generated case name '${name}' is duplicated`);
    if (Object.hasOwn(record, 'fixture')) return failure(`generated case '${name}' may not use fixture`);
    if (typeof record['bucket'] !== 'string' || !BUCKETS.has(record['bucket'])) return failure(`generated case '${name}' needs a bucket from explicit, implicit, contextual, negative, adversarial`);
    const selfCall = typeof record['task'] === 'string' ? selfInvocation(record['task'], skillName) : null;
    if (selfCall !== null) return failure(`generated case '${name}' ${selfCall}`);
    const checks = record['checks'];
    if (checks !== undefined && !Array.isArray(checks)) return failure(`generated case '${name}' has a malformed checks field`);
    for (const check of checks ?? []) {
      if (check === null || typeof check !== 'object' || Array.isArray(check)) return failure(`generated case '${name}' has a malformed check`);
      const entries = Object.entries(check as Record<string, unknown>);
      if (entries.length !== 1 || !CHECK_KINDS.has(entries[0]![0])) return failure(`generated case '${name}' uses a check outside the generation whitelist`);
    }
    const body = Object.fromEntries(Object.entries(record).filter(([key]) => key !== 'name'));
    const parsed = loadCase(YAML.stringify(body, YAML_OPTIONS), name);
    if (!parsed.ok) return failure(parsed.error);
    for (const rel of Object.keys(parsed.value.files)) {
      const violation = casePathViolation(rel);
      if (violation !== null) return failure(`generated case '${name}': ${violation} — keys in files are sandbox-relative paths`);
    }
    const cannotStart = await dryRunCase(parsed.value, scratch);
    if (cannotStart !== null) return failure(`generated ${cannotStart} — setup is executed by /bin/sh -ce in the case sandbox; it must be shell that builds the precondition, not a description of it`);
    files[name] = body;
  }
  if (!Object.values(files).some((entry) => entry['bucket'] === 'adversarial')) return failure('generated cases need at least one adversarial bucket');
  return success(files);
}

const SUITE_SETUP = `git init -q && git add -A -- . ':!.probes' ':!.plants.diff' && git -c user.name=t -c user.email=t@t commit -qm base
for p in .probes/*; do sh "$p" || exit 1; done
git apply .plants.diff
for p in .probes/*; do if sh "$p"; then exit 1; fi; done
rm -rf .probes .plants.diff`;

/** Validate, materialize, load, and dry-run a model-provided ground-truth suite. */
async function validateSuite(raw: Record<string, unknown>, scratch: string, skillName: string | undefined): Promise<Result<string>> {
  if (Object.keys(raw).length !== 1 || raw['suite'] === null || typeof raw['suite'] !== 'object' || Array.isArray(raw['suite'])) return failure("generated suite needs a single 'suite' object");
  const suite = raw['suite'] as Record<string, unknown>;
  const allowedSuite = new Set(['task', 'files', 'plants_diff', 'probes', 'cases']);
  const unknown = Object.keys(suite).find((key) => !allowedSuite.has(key));
  if (unknown !== undefined) return failure(`generated suite may not carry '${unknown}'`);
  if (typeof suite['task'] !== 'string' || !suite['task'].trim()) return failure("generated suite needs a non-empty 'task'");
  const selfCall = selfInvocation(suite['task'], skillName);
  if (selfCall !== null) return failure(`generated suite ${selfCall}`);
  if (suite['files'] === null || typeof suite['files'] !== 'object' || Array.isArray(suite['files']) || Object.keys(suite['files'] as object).length === 0) return failure("generated suite needs a non-empty 'files' map");
  const files: Record<string, string> = {};
  for (const [path, content] of Object.entries(suite['files'] as Record<string, unknown>)) {
    const violation = casePathViolation(path);
    if (violation !== null) return failure(violation);
    if (path === '.plants.diff' || path === '.probes' || path.startsWith('.probes/')) return failure(`generated suite files may not include '${path}'`);
    if (typeof content !== 'string') return failure(`generated suite file '${path}' must be a string`);
    files[path] = content;
  }
  if (typeof suite['plants_diff'] !== 'string' || !suite['plants_diff'].trim()) return failure("generated suite needs a non-empty 'plants_diff'");
  const probesRaw = suite['probes'];
  if (probesRaw === null || typeof probesRaw !== 'object' || Array.isArray(probesRaw) || Object.keys(probesRaw as object).length === 0) return failure("generated suite needs a non-empty 'probes' map");
  const probes: Record<string, string> = {};
  for (const [name, command] of Object.entries(probesRaw as Record<string, unknown>)) {
    if (!CASE_NAME.test(name)) return failure(`generated suite probe '${name}' needs a lowercase-hyphenated name`);
    if (typeof command !== 'string' || !command.trim() || /[\r\n]/.test(command)) return failure(`generated suite probe '${name}' must be a non-empty one-line string`);
    probes[name] = command;
  }
  if (!Array.isArray(suite['cases'])) return failure("generated suite needs a 'cases' list");
  const defects: Record<string, unknown>[] = [];
  const distractors: Record<string, unknown>[] = [];
  const names = new Set<string>();
  const cases: Array<{ name: string; checks: Array<Record<string, string>> }> = [];
  for (const item of suite['cases']) {
    if (item === null || typeof item !== 'object' || Array.isArray(item)) return failure('each generated suite case must be an object');
    const candidate = item as Record<string, unknown>;
    const allowedCase = new Set(['name', 'kind', 'probe', 'checks']);
    const extra = Object.keys(candidate).find((key) => !allowedCase.has(key));
    if (extra !== undefined) return failure(`generated suite case may not carry '${extra}'`);
    const name = candidate['name'];
    if (typeof name !== 'string' || !CASE_NAME.test(name)) return failure("each generated suite case needs a unique lowercase-hyphenated 'name'");
    if (names.has(name)) return failure(`generated suite case name '${name}' is duplicated`);
    names.add(name);
    const kind = candidate['kind'];
    if (kind !== 'defect' && kind !== 'distractor') return failure(`generated suite case '${name}' needs kind defect or distractor`);
    if (kind === 'defect') {
      if (typeof candidate['probe'] !== 'string' || !Object.hasOwn(probes, candidate['probe'])) return failure(`generated suite defect '${name}' names an unknown probe`);
      defects.push(candidate);
    } else {
      if (candidate['probe'] !== undefined) return failure(`generated suite distractor '${name}' may not carry 'probe'`);
      distractors.push(candidate);
    }
    if (!Array.isArray(candidate['checks']) || candidate['checks'].length === 0) return failure(`generated suite case '${name}' needs a non-empty checks list`);
    const checks: Array<Record<string, string>> = [];
    for (const check of candidate['checks']) {
      if (check === null || typeof check !== 'object' || Array.isArray(check)) return failure(`generated suite case '${name}' has a malformed check`);
      const entries = Object.entries(check as Record<string, unknown>);
      if (entries.length !== 1 || (entries[0]![0] !== 'transcript_mentions' && entries[0]![0] !== 'transcript_omits')) return failure(`generated suite case '${name}' uses a check outside the suite whitelist`);
      const [checkKind, anchor] = entries[0]!;
      if (typeof anchor !== 'string' || !anchor.trim()) return failure(`generated suite case '${name}' needs a non-empty check anchor`);
      if ((kind === 'defect' && checkKind !== 'transcript_mentions') || (kind === 'distractor' && checkKind !== 'transcript_omits')) return failure(`generated suite ${kind} '${name}' has the wrong check kind`);
      checks.push({ [checkKind]: anchor });
    }
    cases.push({ name, checks });
  }
  if (defects.length < 2 || defects.length > 6) return failure(`generated suite needs between 2 and 6 defect cases (got ${defects.length})`);
  if (distractors.length !== 1) return failure(`generated suite needs exactly 1 distractor case (got ${distractors.length})`);
  const patchError = await patchApplies(files, suite['plants_diff'] as string, scratch);
  if (patchError !== null) return failure(patchError);
  const materializedFiles: Record<string, string> = { ...files, '.plants.diff': suite['plants_diff'] as string };
  for (const [name, command] of Object.entries(probes)) materializedFiles[`.probes/${name}.sh`] = `${command}\n`;
  const materialized = YAML.stringify({ task: suite['task'], files: materializedFiles, timeout_minutes: 120, requires: [], setup: SUITE_SETUP, cases }, YAML_OPTIONS);
  const loaded = loadSuite(materialized, 'suite');
  if (!loaded.ok) return failure(loaded.error);
  const dryRunError = await dryRunSuite(loaded.value, scratch);
  if (dryRunError !== null) return failure(`generated suite dry run failed: ${dryRunError}`);
  return success(materialized);
}

/**
 * Generated assets are re-read by every hygiene caller (HYG2/HYG3), so the generator must not write
 * anything its own gate refuses. `git config user.email test@test.com` is the idiomatic fixture line
 * a model reaches for, and `test.com` is a real registered domain — it used to plant a HYG3 failure
 * that only surfaced on a later command. `inspectContent` enforces this before the write-back; this
 * sentence is what keeps the model from hitting that refusal in the first place.
 */
const FIXTURE_RULE = 'Any email address you write must use a reserved domain (example.com, example.org, or a .test/.invalid name) — never a real or real-looking one. Never include anything shaped like a credential: no API keys, tokens, passwords, or private keys, real or fake.';

/**
 * Eval-gen spec rev 2 §4 (the engine's §5.1 authoring rule), carried by the v0.20.0 case prompt and
 * dropped from the mode-2 case appendix. One constant so the two prompts cannot drift apart again.
 */
const TASK_RULE = 'Tasks must not demand magic-string incantations and must be answerable without human follow-up.';

/** The frontmatter `name` — the handle a slash command for this skill would use. */
function skillNameOf(skill: string): string | undefined {
  const frontmatter = hygieneFrontmatter(Buffer.from(skill, 'utf8')) as { name?: unknown } | undefined;
  const name = frontmatter?.name;
  return typeof name === 'string' && name.trim() !== '' ? name.trim() : undefined;
}

/**
 * A task that opens with `/<skill-name>` only runs in an arm with the skill staged: the baseline
 * answers "Unknown command" and the case records a loss the skill did not earn (observed live: 5 of
 * 5 generated spec-readable tasks). Returns the correction for the re-ask, or null.
 */
function selfInvocation(task: string, skillName: string | undefined): string | null {
  if (skillName === undefined) return null;
  const escaped = skillName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (!new RegExp(`^/${escaped}(?=$|[\\s:,.;!?)])`, 'i').test(task.trimStart())) return null;
  return `starts its task with /${skillName}: only an arm with the skill staged has that command, so the baseline answers "Unknown command" and scores a false loss. Write the task as the plain request a user would make (what they want done, with the inputs it needs) and let the skill trigger from it; never start it with /${skillName}`;
}

/**
 * Eval-gen D1 (2026-09-14): the runtime contract `execution.ts` enforces, stated where the model can
 * read it. Without this the model filled `setup` with prose ("Assume codex is logged in") that
 * `/bin/sh` ran as a command — rc=127, case dropped — and put files at `/tmp/...`, which the
 * sandbox guard refused. Preconditions are built, then stubbed, then stated; never a reason to
 * drop the case, since the external-state branches are the ones most worth testing.
 */
const SETUP_RULE = 'setup is a POSIX shell script executed by /bin/sh -ce inside the case sandbox (cwd), with a 60-second cap; a non-zero exit drops the case. It must CREATE the precondition, never describe it: no prose, no "Assume ...". If a precondition is the state of an external tool (logged in, quota nearly used, a prior run\'s output), stub that tool: put a small executable script at bin/<tool> in files that answers exactly the invocations the skill makes, and have setup run chmod +x bin/<tool> and export PATH="$PWD/bin:$PATH". If even a stub is impossible, state the assumption inside the task text as something the user tells the agent and leave setup empty. Keys in files are sandbox-relative paths: never absolute, never containing "..", never under .claude/.';

function context(options: GenerateOptions): string {
  // §3.2: in head-to-head the brief is the ENTIRE context. Neither SKILL.md enters this prompt.
  if (options.brief !== undefined) return `TASK BRIEF (the only context; a human has signed off on it):\n${options.brief}`;
  return `SKILL.md:\n${options.skill}\n\nCANDIDATE FILE LISTING (names only):\n${options.files.join('\n')}`;
}

function triggerPrompt(options: GenerateOptions): string {
  return `Generate trigger evaluation assets for this Claude Code skill. Return ONLY JSON with exactly this shape:\n{"should_trigger":["five non-empty prompts"],"should_not_trigger":["five non-empty near-miss prompts"]}\nA should_not_trigger prompt must be a plausible near miss drawn from the endorsed catalog, not an unrelated request.\n${FIXTURE_RULE}\n\nENDORSED CATALOG:\n${options.catalog}\n\n${context(options)}`;
}

export function casePrompt(options: GenerateOptions, floor: number = MIN_CASES): string {
  const subject = options.brief === undefined
    ? 'this Claude Code skill'
    : 'the task brief below. Two different skills will be scored against these cases, so a case must not assume either one\'s conventions';
  return `Generate headlessly answerable execution evaluation cases for ${subject}. Return ONLY JSON: {"cases":[{"name":"lowercase-hyphenated-stem","task":"...","files":{},"setup":"optional shell","checks":[{"transcript_mentions":"..."}],"bucket":"explicit"}]}.\nChoose how many cases this needs, between ${floor} and ${MAX_CASES} inclusive, from its own complexity: a simple job with one way to get it wrong wants ${floor}; a skill with several distinct surfaces, decision branches, or refusal modes wants more, one case per thing that can independently go wrong. Do not pad — a case that tests nothing the others do not is worse than no case.\nEvery case needs a bucket from explicit, implicit, contextual, negative, adversarial; at least one must be adversarial, and a set larger than ${floor} should spread across several buckets rather than repeat one. Do not include fixture. Checks may use ONLY transcript_mentions, transcript_omits, command_matching, no_command_matching, file_exists, file_absent. Do not use command_succeeds. ${TASK_RULE}\n${SETUP_RULE}\n${FIXTURE_RULE}\n\n${context(options)}`;
}

/** §4.1's ground-truth prompt. The contract portion before the case-shape appendix is verbatim. */
function suitePrompt(options: GenerateOptions, fixedShape: GenerationShape): string {
  const fixed = fixedShape === undefined ? '' : `The shape is fixed: return {"${fixedShape}": ${fixedShape === 'suite' ? '...}' : '[...]}'}.\n\n`;
  return `${fixed}Generate evaluation assets for this Claude Code skill so that running it measures
whether the skill does its job, not whether it restates its instructions.

First decide the SHAPE. If you can build a world containing a hidden ground truth the
skill must recover (a repository with planted defects for a reviewer or fixer, a spec
with planted contradictions for an auditor, a session log with facts that must and
must not appear for a summariser), and can name a literal identifier a correct output
must cite, return {"suite": ...} as below. If the skill's behaviour depends on how it
is asked (flags, refusals, protocol steps, wrapping a command), return {"cases": [...]}
in the case shape instead, one case per behaviour. If neither, return cases with a
short "judge" rubric each.

Suite shape — a repository is the example; a spec or log is a single file in files/
with the same rules:

{"suite": {
  "task": "one headlessly answerable instruction, e.g. 'Review the uncommitted diff in this repository before I commit it.'",
  "files": { "<path>": "<full file contents>", ... },
  "plants_diff": "<a unified diff that applies cleanly to files/ with \`git apply\`>",
  "probes": { "<name>": "<shell command, exit 0 on the clean base and non-zero after plants_diff is applied>", ... },
  "cases": [
    { "name": "lowercase-hyphenated-stem", "kind": "defect", "probe": "<probe name>",
      "checks": [ { "transcript_mentions": "<identifier or file:line a correct finding must cite>" } ] },
    { "name": "lowercase-hyphenated-stem", "kind": "distractor",
      "checks": [ { "transcript_omits": "<identifier of the correct code that looks wrong>" } ] }
  ]
}}

Rules.
- The repository: 3 to 6 source files in one language, realistic enough that a
  reviewer must read call sites to judge a change. No package installs; anything the
  probes run must work with the language's standard toolchain already on PATH.
- The defects: between 2 and 6, spread across at least 2 files, each a genuine bug a
  maintainer would fix (wrong sign, off-by-one, broken caller contract, unchecked
  null, swapped arguments, stale invariant). No style issues, no "could be clearer".
  If the SKILL.md states a maximum number of findings, plant fewer than that.
- Exactly one distractor: a change in plants_diff that looks wrong at a glance and is
  correct. Its case uses transcript_omits on an identifier only that change touches.
- Anchors: every defect case's transcript_mentions is an identifier (function, variable,
  constant) or a file:line that a finding about that defect would have to cite. Never
  prose, never a sentence the skill might paraphrase.
- Probes: one per defect. Each is a shell command that exits 0 on the clean base and
  non-zero once plants_diff is applied, proving the defect is real and observable.
  Keep them to one line; \`node -e\`, \`python3 -c\`, or a direct test runner call.
- plants_diff must apply with \`git apply\` to files/ exactly as given. Do not include
  the probes or the diff itself inside files/.
- The task must be answerable with no human follow-up and must not tell the agent
  what to look for.
- Checks may use ONLY transcript_mentions and transcript_omits.
- Do not include fixture, setup, judge, or bucket; the engine writes setup itself.

SKILL.md:
${options.skill}

CANDIDATE FILE LISTING (names only):
${options.files.join('\n')}

Case shape (when you return {"cases": [...]})
Return ONLY JSON: {"cases":[{"name":"lowercase-hyphenated-stem","task":"...","files":{},"setup":"optional shell","checks":[{"transcript_mentions":"..."}],"bucket":"explicit"}]}.
Choose between ${MIN_CASES} and ${MAX_CASES} inclusive from the skill's complexity. ${TASK_RULE} Every case needs a bucket from explicit, implicit, contextual, negative, adversarial; at least one must be adversarial. Checks may use ONLY transcript_mentions, transcript_omits, command_matching, no_command_matching, file_exists, file_absent. Do not use command_succeeds. Do not include fixture. ${SETUP_RULE}
${FIXTURE_RULE}`;
}
