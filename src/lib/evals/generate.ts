/**
 * IE5 eval-gen: pure model orchestration for reviewable local eval assets.  This module never
 * starts Claude itself; `agent.ts` remains the sole process boundary.
 */
import YAML from 'yaml';
import type { AgentApi } from './agent.js';
import { loadCase } from './execution.js';
import { parseTriggers } from './triggers.js';
import { failure, success, type Result } from '../result.js';

const HEADER = '# generated by terum-skills eval-gen — review before trusting';

/** The provenance header every generated asset carries (§3.1: `brief.md` carries it too). */
export function assetHeader(model: string, engineVersion: string, now: Date): string {
  return `${HEADER}\n# model: ${model} · engine: ${engineVersion} · ${now.toISOString()}\n`;
}
const BUCKETS = new Set(['explicit', 'implicit', 'contextual', 'negative', 'adversarial']);
const CHECK_KINDS = new Set(['transcript_mentions', 'command_matching', 'no_command_matching', 'file_exists', 'file_absent']);
const CASE_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
/** §7.3: long enough for a real task description, short enough that a human reads it. */
export const BRIEF_MAX = 1_500;
const DEFAULT_CASES = 3;
const HEAD_TO_HEAD_CASES = 5;

export type NeutralityVerdict =
  | { kind: 'ok' }
  | { kind: 'warn'; name: string }
  | { kind: 'refuse'; name: string };

/**
 * §3.1: the deterministic neutrality check, a PURE function rather than logic inside the
 * correction loop — the supplied-brief path calls it too and must not pay a model round-trip.
 *
 * A multi-token name (hyphenated or spaced) that appears in the brief means the brief is
 * describing the tool, so it refuses. A single-token name is usually an ordinary English word
 * — this project ships skills called `search`, `eval`, `ls`, `run` — and a hard refusal there
 * makes those skills uncomparable, so it warns and continues. No dictionary: the rule is the
 * token count of the NAME, so there is nothing to maintain.
 */
export function checkBriefNeutrality(brief: string, names: readonly string[]): NeutralityVerdict {
  let warned: string | undefined;
  for (const name of names) {
    if (!nameAppears(brief, name)) continue;
    if (name.split(/[^A-Za-z0-9]+/).filter(Boolean).length > 1) return { kind: 'refuse', name };
    warned ??= name;
  }
  return warned === undefined ? { kind: 'ok' } : { kind: 'warn', name: warned };
}

/** Bounded by non-alphanumerics so `ls` does not match inside `tools` or `false`. */
function nameAppears(haystack: string, name: string): boolean {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![A-Za-z0-9])${escaped}(?![A-Za-z0-9])`, 'i').test(haystack);
}

export interface GeneratedCases {
  files: Record<string, string>;
  names: string[];
}

export interface GeneratedAssets {
  cases?: GeneratedCases;
  triggers?: string;
}

export interface DeriveBriefOptions {
  agent: AgentApi;
  /** Both skills, each with its SKILL.md and its file listing. Order here is irrelevant. */
  skills: readonly { name: string; skill: string; files: readonly string[] }[];
  model: string;
}

export interface DerivedBrief {
  brief: string;
  /** §4 `_meta.brief_order`: the names in the order they were shown, so aliasing is auditable. */
  order: string[];
  /** Set when a single-token name survived into the brief — printed above the confirm gate. */
  warning?: string;
}

/**
 * §3.1: derive the shared task brief. Both skills are aliased to `Skill 1` / `Skill 2` and
 * ordered BY NAME, never by which was typed first — a fixed order would put the candidate in
 * the same slot on every run, which is the position tilt §7.5 swaps orderings to avoid.
 */
export async function deriveBrief(options: DeriveBriefOptions): Promise<Result<DerivedBrief>> {
  const ordered = [...options.skills].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const names = ordered.map((entry) => entry.name);
  let warning: string | undefined;
  const result = await askWithValidation(options.agent, briefPrompt(ordered), options.model, (raw) => {
    const brief = raw['brief'];
    if (typeof brief !== 'string' || !brief.trim()) return failure("the brief must be a non-empty 'brief' string");
    if (brief.length > BRIEF_MAX) return failure(`the brief must be at most ${BRIEF_MAX} characters (got ${brief.length})`);
    const neutrality = checkBriefNeutrality(brief, names);
    if (neutrality.kind === 'refuse') return failure(`the brief names '${neutrality.name}'; describe the job, not either tool`);
    warning = neutrality.kind === 'warn' ? neutrality.name : undefined;
    return success(brief.trim());
  });
  if (!result.ok) return failure(`Could not derive a shared brief: ${result.error}. Write one yourself and pass --brief <path>.`);
  return success({ brief: result.value, order: names, ...(warning === undefined ? {} : { warning }) });
}

function briefPrompt(ordered: readonly { skill: string; files: readonly string[] }[]): string {
  const blocks = ordered.map((entry, index) => `SKILL ${index + 1} — SKILL.md:\n${entry.skill}\n\nSKILL ${index + 1} — FILE LISTING (names only):\n${entry.files.join('\n')}`);
  return `Two Claude Code skills do a similar job. Describe THE JOB — not either skill — as a task brief that an evaluator will use to write test cases neither skill has seen.\n\nReturn ONLY JSON: {"brief":"..."}.\nThe brief must be plain prose, at most ${BRIEF_MAX} characters, and must NOT name either skill or any tool: a brief that names a tool is describing the tool, not the job. Describe what someone needs done and what a good result looks like.\n\n${blocks.join('\n\n')}`;
}

export interface GenerateOptions {
  agent: AgentApi;
  /** Full candidate SKILL.md, deliberately unblinded under the accepted-risk ruling. */
  skill: string;
  /** Candidate-relative names only; contents besides SKILL.md never enter a generation prompt. */
  files: readonly string[];
  /** Endorsed catalog, used to create meaningful trigger near-misses. */
  catalog: string;
  model: string;
  engineVersion: string;
  now: Date;
  cases?: boolean;
  triggers?: boolean;
  /**
   * §3.2: head-to-head. When set, the case prompt sees the brief ALONE — no SKILL.md, no file
   * listing — and generates five rubric-carrying cases instead of three check-only ones.
   */
  brief?: string;
  /** Skill names the generated rubrics must not contain (§3.1); only meaningful with `brief`. */
  rivalNames?: readonly string[];
}

/** Generate each requested asset kind with at most two validation-correction re-asks. */
export async function generate(options: GenerateOptions): Promise<Result<GeneratedAssets>> {
  const header = assetHeader(options.model, options.engineVersion, options.now);
  const out: GeneratedAssets = {};
  if (options.triggers) {
    const generated = await askWithValidation(options.agent, triggerPrompt(options), options.model, validateTriggers);
    if (!generated.ok) return failure(`Could not generate triggers: ${generated.error}. Retry the command or pass --no-gen.`);
    out.triggers = header + YAML.stringify(generated.value);
  }
  if (options.cases) {
    const count = options.brief === undefined ? DEFAULT_CASES : HEAD_TO_HEAD_CASES;
    const generated = await askWithValidation(options.agent, casePrompt(options), options.model,
      (raw) => validateCases(raw, count, options.brief !== undefined ? (options.rivalNames ?? []) : null));
    if (!generated.ok) return failure(`Could not generate execution cases: ${generated.error}. Retry the command or pass --no-gen.`);
    const files: Record<string, string> = {};
    for (const [name, value] of Object.entries(generated.value)) files[`${name}.yaml`] = header + YAML.stringify(value);
    out.cases = { files, names: Object.keys(generated.value) };
  }
  return success(out);
}

async function askWithValidation<T>(agent: AgentApi, prompt: string, model: string, validate: (raw: Record<string, unknown>) => Result<T>): Promise<Result<T>> {
  let correction = '';
  let lastError = 'model returned no usable response';
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const raw = await agent.askJson(prompt + correction, { model });
      const parsed = validate(raw);
      if (parsed.ok) return parsed;
      lastError = parsed.error;
    } catch (error) {
      lastError = error instanceof Error ? error.message : String(error);
    }
    correction = `\n\nYour previous response could not be used: ${lastError}\nReturn a corrected JSON object only, following every required shape and count.`;
  }
  return failure(lastError);
}

function validateTriggers(raw: Record<string, unknown>): Result<Record<string, unknown>> {
  const source = YAML.stringify(raw);
  const parsed = parseTriggers(source);
  if (!parsed.ok) return failure(parsed.error);
  if (parsed.value.shouldTrigger.length !== 5) return failure(`generated triggers need exactly 5 should_trigger prompts (got ${parsed.value.shouldTrigger.length})`);
  if (parsed.value.shouldNotTrigger.length !== 5) return failure(`generated triggers need exactly 5 should_not_trigger prompts (got ${parsed.value.shouldNotTrigger.length})`);
  if (parsed.value.shouldTrigger.some((prompt) => !prompt.trim()) || parsed.value.shouldNotTrigger.some((prompt) => !prompt.trim())) return failure('generated trigger prompts must be non-empty strings');
  return success({ should_trigger: parsed.value.shouldTrigger, should_not_trigger: parsed.value.shouldNotTrigger });
}

/**
 * `requireRubric` is null outside head-to-head; inside it, it carries the skill names the
 * rubric must not contain (§3.1) — a rubric is read by the judge, so it is as load-bearing
 * for neutrality as the brief itself.
 */
function validateCases(raw: Record<string, unknown>, count: number, requireRubric: readonly string[] | null): Result<Record<string, Record<string, unknown>>> {
  const supplied = raw['cases'];
  if (!Array.isArray(supplied)) return failure("generated cases need a 'cases' array");
  if (supplied.length !== count) return failure(`generated cases need exactly ${count} cases (got ${supplied.length})`);
  const files: Record<string, Record<string, unknown>> = {};
  for (const candidate of supplied) {
    if (candidate === null || typeof candidate !== 'object' || Array.isArray(candidate)) return failure('each generated case must be an object');
    const record = candidate as Record<string, unknown>;
    const name = record['name'];
    if (typeof name !== 'string' || !CASE_NAME.test(name)) return failure("each generated case needs a unique lowercase-hyphenated 'name'");
    if (Object.hasOwn(files, name)) return failure(`generated case name '${name}' is duplicated`);
    if (Object.hasOwn(record, 'fixture')) return failure(`generated case '${name}' may not use fixture`);
    if (typeof record['bucket'] !== 'string' || !BUCKETS.has(record['bucket'])) return failure(`generated case '${name}' needs a bucket from explicit, implicit, contextual, negative, adversarial`);
    if (requireRubric !== null) {
      // §3.2: without a rubric `decide()` returns checks-equal-no-judge whenever both arms
      // agree on checks — the normal outcome for two skills that both work.
      const judge = record['judge'];
      if (typeof judge !== 'string' || judge.trim().split(/(?<=[.!?])\s+/).filter((part) => part.trim()).length < 2) {
        return failure(`generated case '${name}' needs a 'judge' rubric of 2-4 sentences saying what a better answer looks like`);
      }
      const neutrality = checkBriefNeutrality(judge, requireRubric);
      if (neutrality.kind === 'refuse') return failure(`generated case '${name}' has a judge rubric naming '${neutrality.name}'; rubrics describe a good answer, never a tool`);
    }
    const checks = record['checks'];
    if (checks !== undefined && !Array.isArray(checks)) return failure(`generated case '${name}' has a malformed checks field`);
    for (const check of checks ?? []) {
      if (check === null || typeof check !== 'object' || Array.isArray(check)) return failure(`generated case '${name}' has a malformed check`);
      const entries = Object.entries(check as Record<string, unknown>);
      if (entries.length !== 1 || !CHECK_KINDS.has(entries[0]![0])) return failure(`generated case '${name}' uses a check outside the generation whitelist`);
    }
    const body = Object.fromEntries(Object.entries(record).filter(([key]) => key !== 'name'));
    const parsed = loadCase(YAML.stringify(body), name);
    if (!parsed.ok) return failure(parsed.error);
    files[name] = body;
  }
  if (!Object.values(files).some((entry) => entry['bucket'] === 'adversarial')) return failure('generated cases need at least one adversarial bucket');
  return success(files);
}

function context(options: GenerateOptions): string {
  // §3.2: in head-to-head the brief is the ENTIRE context. Neither SKILL.md enters this
  // prompt, which removes eval-gen's accepted circularity rather than mitigating it.
  if (options.brief !== undefined) return `TASK BRIEF (the only context; a human has signed off on it):\n${options.brief}`;
  return `SKILL.md:\n${options.skill}\n\nCANDIDATE FILE LISTING (names only):\n${options.files.join('\n')}`;
}

function triggerPrompt(options: GenerateOptions): string {
  return `Generate trigger evaluation assets for this Claude Code skill. Return ONLY JSON with exactly this shape:\n{"should_trigger":["five non-empty prompts"],"should_not_trigger":["five non-empty near-miss prompts"]}\nA should_not_trigger prompt must be a plausible near miss drawn from the endorsed catalog, not an unrelated request.\n\nENDORSED CATALOG:\n${options.catalog}\n\n${context(options)}`;
}

function casePrompt(options: GenerateOptions): string {
  const headToHead = options.brief !== undefined;
  const count = headToHead ? HEAD_TO_HEAD_CASES : DEFAULT_CASES;
  const shape = `{"cases":[{"name":"lowercase-hyphenated-stem","task":"...","files":{},"setup":"optional","checks":[{"transcript_mentions":"..."}]${headToHead ? ',"judge":"2-4 sentences on what a better answer looks like"' : ''},"bucket":"explicit"}]}`;
  const subject = headToHead
    ? "the task brief below. Two different skills will be scored against these cases, so a case must not assume either one's conventions"
    : 'this Claude Code skill';
  // §3.2: the rubric is what makes the judge reachable at all — two competent skills pass the
  // same checks, and a check tie with no rubric is a tie, not a comparison.
  const rubricRule = headToHead
    ? '\nEvery case also needs a "judge" rubric: 2-4 sentences describing what distinguishes a better response for THIS task. The rubric decides check ties, so it must be about the quality of the work, and must never name a tool or skill.'
    : '';
  return `Generate exactly ${count === DEFAULT_CASES ? 'three' : 'five'} headlessly answerable execution evaluation cases for ${subject}. Return ONLY JSON: ${shape}.\nEvery case needs a bucket from explicit, implicit, contextual, negative, adversarial; at least one must be adversarial. Do not include fixture. Checks may use ONLY transcript_mentions, command_matching, no_command_matching, file_exists, file_absent. Do not use command_succeeds. Tasks must not demand magic-string incantations and must be answerable without human follow-up.${rubricRule}\n\n${context(options)}`;
}
